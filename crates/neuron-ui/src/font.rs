/// The glyph index of a character (the index of `?` when it is not in the font).
pub fn index(c: char) -> usize {
    let c = c.to_ascii_uppercase();
    CHARS
        .chars()
        .position(|x| x == c)
        .unwrap_or(CHARS.len() - 1)
}

/// The font as a C array definition.
pub fn c_table() -> String {
    let mut s = String::from("const uint8_t nrt_ui_font[45][7] = {\n");
    for (g, c) in GLYPHS.iter().zip(CHARS.chars()) {
        let rows: Vec<String> = g.iter().map(|r| format!("0x{r:02x}")).collect();
        s.push_str(&format!(
            "  {{ {} }}, /* {} */\n",
            rows.join(", "),
            if c == ' ' {
                "space".to_string()
            } else {
                c.to_string()
            }
        ));
    }
    s.push_str("};\n");
    s.push_str(&format!("const char nrt_ui_chars[] = \"{CHARS}\";\n"));
    s
}
