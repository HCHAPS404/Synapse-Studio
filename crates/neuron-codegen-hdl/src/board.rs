//! FPGA boards and their pin constraint files (PCF for iCE40, XDC for 7-series).

use crate::emit::Verilog;
use crate::HdlDiag;
use serde::Deserialize;

/// FPGA family: decides the constraint format and the tool flow.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Family {
    /// Lattice iCE40 (yosys, nextpnr-ice40, icepack; PCF constraints).
    Ice40,
    /// Xilinx 7-series (yosys or Vivado; XDC constraints).
    Xc7,
}

/// An FPGA board description (`targets/fpga/<name>.fpga.toml`).
#[derive(Debug, Clone, PartialEq, Deserialize)]
pub struct FpgaBoard {
    /// Schema version.
    pub schema: u32,
    /// Name, the file stem.
    pub name: String,
    /// Origin of the facts.
    pub source: String,
    /// Trust level (`community`).
    pub trust: String,
    /// Family.
    pub family: Family,
    /// Device part (`xc7a35tcpg236-1`, `up5k`).
    pub part: String,
    /// Package (`cpg236`, `sg48`).
    pub package: String,
    /// I/O standard written in XDC files.
    #[serde(default = "default_iostd")]
    pub io_standard: String,
    /// Package pins that user logic may use; empty means "not checked".
    #[serde(default)]
    pub pins: Vec<String>,
    /// Arguments of `openFPGALoader` for this board (`["-b", "..."]`).
    #[serde(default)]
    pub loader_args: Vec<String>,
    /// Free text.
    #[serde(default)]
    pub note: String,
}

fn default_iostd() -> String {
    "LVCMOS33".into()
}

const BUILTIN: &[(&str, &str)] = &[
    (
        "artix7_35t_board",
        include_str!("../../../targets/fpga/artix7_35t_board.fpga.toml"),
    ),
    (
        "ice40up5k_breakout",
        include_str!("../../../targets/fpga/ice40up5k_breakout.fpga.toml"),
    ),
];

impl FpgaBoard {
    /// Names of the embedded boards.
    pub fn names() -> Vec<&'static str> {
        BUILTIN.iter().map(|(n, _)| *n).collect()
    }

    /// An embedded board, or `None`.
    pub fn builtin(name: &str) -> Option<FpgaBoard> {
        BUILTIN
            .iter()
            .find(|(n, _)| *n == name)
            .and_then(|(_, text)| FpgaBoard::parse(text).ok())
    }

    /// Parses a board file.
    pub fn parse(text: &str) -> Result<FpgaBoard, String> {
        let b: FpgaBoard = toml::from_str(text).map_err(|e| e.to_string())?;
        if b.schema != 1 {
            return Err(format!("unsupported schema {}", b.schema));
        }
        Ok(b)
    }
}

/// The constraint file of the top module of `v` for `board`: PCF for iCE40, XDC for 7-series.
/// A port without `@ pin(...)` is left to the tools; a pin that the board does not list is
/// `NE0603`.
pub fn emit_constraints(v: &Verilog, top: &str, board: &FpgaBoard) -> Result<String, Vec<HdlDiag>> {
    let Some((_, ports)) = v.ports.iter().find(|(m, _)| m == top) else {
        return Err(vec![HdlDiag {
            code: "NE0610",
            message: format!("there is no circuit `{top}` to constrain"),
            help: Some(format!("circuits: {}", v.modules.join(", "))),
            file: String::new(),
            span: [0, 0],
        }]);
    };
    let mut diags = Vec::new();
    let mut out = String::new();
    out.push_str(&format!(
        "# Generated by neuron-codegen-hdl for `{top}` on `{}` ({} {}).\n",
        board.name, board.part, board.package
    ));
    for p in ports {
        if p.pins.is_empty() {
            continue;
        }
        if p.pins.len() != p.width as usize && p.pins.len() != 1 {
            diags.push(HdlDiag {
                code: "NE0603",
                message: format!(
                    "port `{}` has {} bits but {} pins",
                    p.name,
                    p.width,
                    p.pins.len()
                ),
                help: Some("list one pin per bit, bit 0 first".into()),
                file: String::new(),
                span: [0, 0],
            });
            continue;
        }
        for (bit, pin) in p.pins.iter().enumerate() {
            if !board.pins.is_empty() && !board.pins.contains(pin) {
                diags.push(HdlDiag {
                    code: "NE0603",
                    message: format!(
                        "pin `{pin}` of port `{}` is not a user pin of `{}`",
                        p.name, board.name
                    ),
                    help: Some(format!("user pins: {}", board.pins.join(", "))),
                    file: String::new(),
                    span: [0, 0],
                });
                continue;
            }
            let port = if p.width > 1 {
                format!("{}[{bit}]", p.name)
            } else {
                p.name.clone()
            };
            match board.family {
                Family::Ice40 => out.push_str(&format!("set_io {port} {pin}\n")),
                Family::Xc7 => out.push_str(&format!(
                    "set_property -dict {{ PACKAGE_PIN {pin} IOSTANDARD {} }} [get_ports {{ {port} }}]\n",
                    board.io_standard
                )),
            }
        }
        if let Some(hz) = p.clock_hz.filter(|h| *h > 0) {
            let period_ns = 1e9 / hz as f64;
            match board.family {
                Family::Ice40 => out.push_str(&format!("# clock {} at {hz} Hz (period {period_ns:.3} ns, given to nextpnr with --freq)\n", p.name)),
                Family::Xc7 => out.push_str(&format!(
                    "create_clock -add -name {0}_clk -period {period_ns:.3} [get_ports {{ {0} }}]\n",
                    p.name
                )),
            }
        }
    }
    if diags.is_empty() {
        Ok(out)
    } else {
        Err(diags)
    }
}
