const CONSTRUCTS: &[&str] = &[
    "inputs/outputs/memory",
    "rung",
    "set/reset",
    "ton/tof/tp",
    "ctu/ctd/ctud",
    "r_trig/f_trig",
    "sr/rs",
    "hysteresis/debounce/ramp/lowpass/highpass/moving_average/pid",
    "when",
    "sequence",
    "fsm",
    "safety",
];

pub(crate) fn plc_modules(nir: &Nir) -> Vec<usize> {
    nir.modules
        .iter()
        .enumerate()
        .filter(|(_, m)| m.dialect == "plc")
        .map(|(i, _)| i)
        .collect()
}

pub(crate) fn no_plc(nir: &Nir) -> Vec<Diag> {
    vec![Diag {
        code: "NE0610",
        message: "the program has no `plc` module to translate".into(),
        help: Some("an IEC 61131-3 emitter reads modules declared `module name for plc`".into()),
        file: nir
            .modules
            .first()
            .map(|m| m.file.clone())
            .unwrap_or_default(),
        span: [0, 0],
    }]
}

fn header(g: &Gen, comment: &str) -> String {
    format!(
        "{comment} {}: generated by Neuron {} from {}. Change the .neuron source, not this file.",
        g.name,
        env!("CARGO_PKG_VERSION"),
        g.file
    )
}

/// Wiring and configuration report of one program.
pub(crate) fn wiring(g: &Gen, addr: impl Fn(&str) -> String) -> String {
    let mut s = format!("## Program `{}` (from `{}`)\n\n", g.name, g.file);
    s.push_str(&format!(
        "Run it in a cyclic task with an interval of {} ms.\n\n",
        g.scan_ns as f64 / 1e6
    ));
    s.push_str("| Signal | Direction | Address | Type |\n|---|---|---|---|\n");
    for (dir, vars) in [
        ("input", &g.inputs),
        ("output", &g.outputs),
        ("memory", &g.memory),
    ] {
        for v in vars.iter() {
            let a =
                v.at.as_deref()
                    .map_or_else(|| "symbolic (map it in the project)".to_string(), &addr);
            s.push_str(&format!("| `{}` | {dir} | {a} | {} |\n", v.name, v.ty));
        }
    }
    if !g.faults.is_empty() {
        s.push_str("\nFault codes in `neuron_fault_code` (0 means no fault):\n\n| Code | Fault |\n|---|---|\n");
        for (i, f) in g.faults.iter().enumerate() {
            s.push_str(&format!("| {} | `{f}` |\n", i + 1));
        }
    }
    s.push_str(
        "\nThe program holds the safe state while `neuron_fault` is TRUE. It is a design aid, not a \
         certified safety function: a hardwired emergency stop remains the authority.\n\n",
    );
    s
}

fn section(w: &mut Writer, kw: &str, comment: &str, decls: &[String]) {
    if decls.is_empty() {
        return;
    }
    w.line(&format!("{kw} (* {comment} *)"));
    w.indent();
    for d in decls {
        w.line(d);
    }
    w.dedent();
    w.line("END_VAR");
}

/// The Structured Text emitter (`neuron emit st`).
pub struct St;

impl Emitter for St {
    fn manifest(&self) -> Manifest {
        Manifest {
            name: "st",
            language: "IEC 61131-3 Structured Text",
            dialects: &["plc"],
            profiles: &["generic", "yaskawa"],
            constructs: CONSTRUCTS,
        }
    }

    fn emit(&self, nir: &Nir, opts: &EmitOptions) -> Result<Package, Vec<Diag>> {
        let profile = if opts.profile.is_empty() {
            "generic"
        } else {
            opts.profile.as_str()
        };
        if !matches!(profile, "generic" | "yaskawa") {
            return Err(vec![Diag {
                code: "NE0610",
                message: format!("unknown Structured Text profile `{profile}`"),
                help: Some("use `generic` or `yaskawa`".into()),
                file: String::new(),
                span: [0, 0],
            }]);
        }
        let mods = plc_modules(nir);
        if mods.is_empty() {
            return Err(no_plc(nir));
        }
        let mut fid = Fidelity::new("emit-st", &format!("plc.{profile}"));
        let mut pkg = Package::new(fid.clone());
        let mut diags = Vec::new();
        let mut helpers: BTreeSet<&'static str> = BTreeSet::new();
        let mut programs: Vec<(String, i64)> = Vec::new();
        let mut globals = Writer::new("    ");
        let mut wiring_text =
            format!("# Wiring and configuration (Structured Text, profile `{profile}`)\n\n");
        for m in mods {
            let mut g = Gen::new(nir, m, Style::Iec, Fidelity::new("emit-st", ""));
            let body = g.body("    ");
            diags.append(&mut g.diags);
            helpers.extend(g.helpers.iter().copied());
            programs.push((g.name.clone(), g.scan_ns));
            wiring_text.push_str(&wiring(&g, |a| a.to_string()));
            let mut w = Writer::new("    ");
            w.line(&header(&g, "(*"));
            w.line("*)");
            w.line(&format!("PROGRAM {}", g.name));
            let addressed = |vs: &[PVar]| {
                vs.iter()
                    .filter(|v| v.at.is_some())
                    .map(|v| g.decl(v))
                    .collect::<Vec<_>>()
            };
            let symbolic = |vs: &[PVar]| {
                vs.iter()
                    .filter(|v| v.at.is_none())
                    .map(|v| g.decl(v))
                    .collect::<Vec<_>>()
            };
            if profile == "yaskawa" {
                // I/O with addresses go to the global variable list; the program sees them as externals.
                let all: Vec<&PVar> = g
                    .inputs
                    .iter()
                    .chain(&g.outputs)
                    .chain(&g.memory)
                    .filter(|v| v.at.is_some())
                    .collect();
                globals.line(&format!("(* I/O of program {} *)", g.name));
                for v in &all {
                    globals.line(&g.decl(v));
                }
                let ext: Vec<String> = all
                    .iter()
                    .map(|v| format!("{} : {};", v.name, v.ty))
                    .collect();
                section(
                    &mut w,
                    "VAR_EXTERNAL",
                    "global I/O, declared in GlobalVars.st",
                    &ext,
                );
            } else {
                section(&mut w, "VAR", "inputs", &addressed(&g.inputs));
                section(&mut w, "VAR", "outputs", &addressed(&g.outputs));
                let (ret, plain): (Vec<&PVar>, Vec<&PVar>) = g
                    .memory
                    .iter()
                    .filter(|v| v.at.is_some())
                    .partition(|v| v.retain);
                section(
                    &mut w,
                    "VAR RETAIN",
                    "memory",
                    &ret.iter().map(|v| g.decl(v)).collect::<Vec<_>>(),
                );
                section(
                    &mut w,
                    "VAR",
                    "memory",
                    &plain.iter().map(|v| g.decl(v)).collect::<Vec<_>>(),
                );
            }
            section(
                &mut w,
                "VAR_INPUT",
                "inputs without an address",
                &symbolic(&g.inputs),
            );
            section(
                &mut w,
                "VAR_OUTPUT",
                "outputs without an address",
                &symbolic(&g.outputs),
            );
            section(
                &mut w,
                "VAR",
                "memory without an address",
                &symbolic(&g.memory),
            );
            let consts: Vec<String> = g
                .locals
                .iter()
                .filter(|v| v.constant)
                .map(|v| g.decl(v))
                .collect();
            section(&mut w, "VAR CONSTANT", "constants", &consts);
            let mut statics: Vec<String> = g
                .locals
                .iter()
                .filter(|v| !v.constant)
                .map(|v| g.decl(v))
                .collect();
            statics.extend(g.blocks.iter().map(|b| g.block_decl(b)));
            section(&mut w, "VAR", "function blocks and variables", &statics);
            section(&mut w, "VAR", "generated state", &g.state_decls());
            w.append(body);
            w.line("END_PROGRAM");
            pkg.add(&format!("{}.st", g.name), w);
            fid.merge(g.fid);
        }
        if !helpers.is_empty() {
            let mut text =
                String::from("(* Function blocks of std.control, generated by Neuron. *)\n");
            for h in &helpers {
                text.push('\n');
                text.push_str(&helpers::helper(h, Style::Iec, "    "));
            }
            pkg.add_text("NeuronLib.st", text);
        }
        if profile == "yaskawa" {
            let (text, _) = globals.finish();
            pkg.add_text("GlobalVars.st", format!("VAR_GLOBAL\n{text}END_VAR\n"));
            wiring_text.push_str(
                "Profile `yaskawa`: import `GlobalVars.st` as the global variable list, then each program, and \
                 configure the task in the project. The details of this profile are confirmed in hardware \
                 session I5.\n",
            );
        } else {
            let mut c =
                String::from("CONFIGURATION neuron_config\n    RESOURCE neuron_resource ON PLC\n");
            for (i, (name, ns)) in programs.iter().enumerate() {
                c.push_str(&format!(
                    "        TASK task{i} (INTERVAL := {}, PRIORITY := 1);\n",
                    crate::nirx::iec_time(*ns)
                ));
                c.push_str(&format!(
                    "        PROGRAM {name}_instance WITH task{i} : {name};\n"
                ));
            }
            c.push_str("    END_RESOURCE\nEND_CONFIGURATION\n");
            pkg.add_text("config.st", c);
        }
        if !diags.is_empty() {
            return Err(diags);
        }
        pkg.wiring = wiring_text;
        pkg.fidelity = fid;
        Ok(pkg)
    }
}

/// SCL type spelling of an IEC type (`BOOL` -> `Bool`).
pub(crate) fn scl_type(t: &str) -> String {
    match t {
        "BOOL" => "Bool",
        "SINT" => "SInt",
        "INT" => "Int",
        "DINT" => "DInt",
        "LINT" => "LInt",
        "USINT" => "USInt",
        "UINT" => "UInt",
        "UDINT" => "UDInt",
        "ULINT" => "ULInt",
        "REAL" => "Real",
        "LREAL" => "LReal",
        "TIME" => "Time",
        "STRING" => "String",
        other => other,
    }
    .to_string()
}

/// Siemens-style address: `%IX0.0` -> `%I0.0`.
pub(crate) fn s7_addr(a: &str) -> String {
    let b = a.as_bytes();
    if b.len() > 3 && b[0] == b'%' && b[2] == b'X' {
        format!("%{}{}", b[1] as char, &a[3..])
    } else {
        a.to_string()
    }
}

/// The SCL emitter (`neuron emit scl`).
pub struct Scl;

impl Emitter for Scl {
    fn manifest(&self) -> Manifest {
        Manifest {
            name: "scl",
            language: "Siemens-style SCL",
            dialects: &["plc"],
            profiles: &["s7"],
            constructs: CONSTRUCTS,
        }
    }

    fn emit(&self, nir: &Nir, _opts: &EmitOptions) -> Result<Package, Vec<Diag>> {
        let mods = plc_modules(nir);
        if mods.is_empty() {
            return Err(no_plc(nir));
        }
        let mut fid = Fidelity::new("emit-scl", "plc.s7");
        let mut pkg = Package::new(fid.clone());
        let mut diags = Vec::new();
        let mut tags = String::from("Name,Data Type,Logical Address,Comment\n");
        let mut wiring_text = String::from("# Wiring and configuration (SCL)\n\n");
        let mut helpers: BTreeSet<&'static str> = BTreeSet::new();
        for m in mods {
            let mut g = Gen::new(nir, m, Style::Scl, Fidelity::new("emit-scl", ""));
            let body = g.body("   ");
            diags.append(&mut g.diags);
            helpers.extend(g.helpers.iter().copied());
            wiring_text.push_str(&wiring(&g, s7_addr));
            wiring_text.push_str(&format!(
                "Create `Neuron_Cyclic_{0}` as a cyclic interrupt organization block with an interval of {1} ms, \
                 and the instance data block `{0}_DB`.\n\n",
                g.name,
                g.scan_ns as f64 / 1e6
            ));
            let decl = |v: &PVar| {
                let init = v
                    .init
                    .as_ref()
                    .map_or(String::new(), |i| format!(" := {i}"));
                format!("{} : {}{init};", v.name, scl_type(&v.ty))
            };
            let mut w = Writer::new("   ");
            w.line(&header(&g, "//"));
            w.line(&format!("FUNCTION_BLOCK \"{}\"", g.name));
            w.line("{ S7_Optimized_Access := 'TRUE' }");
            w.line("VERSION : 0.1");
            w.indent();
            let block = |w: &mut Writer, kw: &str, lines: Vec<String>| {
                if lines.is_empty() {
                    return;
                }
                w.line(kw);
                w.indent();
                for l in lines {
                    w.line(&l);
                }
                w.dedent();
                w.line("END_VAR");
            };
            block(&mut w, "VAR_INPUT", g.inputs.iter().map(decl).collect());
            block(&mut w, "VAR_OUTPUT", g.outputs.iter().map(decl).collect());
            block(
                &mut w,
                "VAR RETAIN",
                g.memory.iter().filter(|v| v.retain).map(decl).collect(),
            );
            let mut statics: Vec<String> =
                g.memory.iter().filter(|v| !v.retain).map(decl).collect();
            statics.extend(g.locals.iter().filter(|v| !v.constant).map(decl));
            statics.extend(
                g.blocks
                    .iter()
                    .map(|b| format!("{} : {};", b.name, g.std_type(&b.kind))),
            );
            statics.extend(g.state.iter().map(decl));
            if !g.faults.is_empty()
                || g.state_decls()
                    .iter()
                    .any(|d| d.starts_with("neuron_fault"))
            {
                statics.push("neuron_fault : Bool;".into());
                statics.push("neuron_fault_code : Int;".into());
            }
            block(&mut w, "VAR", statics);
            block(
                &mut w,
                "VAR CONSTANT",
                g.locals.iter().filter(|v| v.constant).map(decl).collect(),
            );
            w.dedent();
            w.line("BEGIN");
            w.append(body);
            w.line("END_FUNCTION_BLOCK");
            w.line("");
            w.line(&format!("ORGANIZATION_BLOCK \"Neuron_Cyclic_{}\"", g.name));
            w.line("{ S7_Optimized_Access := 'TRUE' }");
            w.line("VERSION : 0.1");
            w.line("BEGIN");
            let mut args: Vec<String> = g
                .inputs
                .iter()
                .map(|v| format!("{0} := \"{0}\"", v.name))
                .collect();
            args.extend(g.outputs.iter().map(|v| format!("{0} => \"{0}\"", v.name)));
            w.line(&format!("   \"{}_DB\"({});", g.name, args.join(", ")));
            w.line("END_ORGANIZATION_BLOCK");
            for v in g.inputs.iter().chain(&g.outputs).chain(&g.memory) {
                let a = v.at.as_deref().map(s7_addr).unwrap_or_default();
                tags.push_str(&format!(
                    "{},{},{a},{} of {}\n",
                    v.name,
                    scl_type(&v.ty),
                    if g.inputs.iter().any(|x| x.name == v.name) {
                        "input"
                    } else if g.outputs.iter().any(|x| x.name == v.name) {
                        "output"
                    } else {
                        "memory"
                    },
                    g.name
                ));
            }
            if g.memory.iter().any(|v| v.at.is_some()) {
                let f = g.file.clone();
                g.fid.record(
                    &f,
                    [0, 0],
                    Class::Equivalent,
                    "memory addresses",
                    "memory variables live in the instance data block; their addresses are listed in PLC_tags.csv for reference",
                );
            }
            pkg.add(&format!("{}.scl", g.name), w);
            fid.merge(g.fid);
        }
        if !helpers.is_empty() {
            let mut text =
                String::from("// Function blocks of std.control, generated by Neuron.\n");
            for h in &helpers {
                text.push('\n');
                text.push_str(&helpers::helper(h, Style::Scl, "   "));
            }
            pkg.add_text("NeuronLib.scl", text);
        }
        pkg.add_text("PLC_tags.csv", tags);
        if !diags.is_empty() {
            return Err(diags);
        }
        pkg.wiring = wiring_text;
        pkg.fidelity = fid;
        Ok(pkg)
    }
}
