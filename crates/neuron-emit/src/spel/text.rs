//! Fixed program text of the spel emitter: the workspace check and the slave.
//!
//! Both files use statements that need the real controller to confirm (network, reading the
//! position of a point). They are marked "to confirm in session I6".

use super::WORKSPACE_ERROR;
use crate::nirx::fmt_num;
use crate::robot::Robot;

/// `NeuronLib.prg`: `NeuronCheck`, called before a motion whose target is computed.
pub(super) fn lib(r: &Robot) -> String {
    let mut s = String::new();
    s.push_str("' NeuronLib.prg: generated by Neuron. Called by the generated programs and by NeuronSlave.prg.\n");
    s.push_str(&format!(
        "' Limits come from the robot manifest `{}`.\n",
        r.name
    ));
    s.push_str(
        "' Dialect details marked \"to confirm in session I6\" need the real controller.\n\n",
    );
    s.push_str("Function NeuronCheck(n As Integer)\n");
    s.push_str("  Real x, y, z, d\n");
    s.push_str("  Integer j\n");
    s.push_str(&format!(
        "  ' Cartesian point: position after the local transform of the point (to confirm in session I6).\n  x = CX(P(n))\n  y = CY(P(n))\n  z = CZ(P(n))\n  d = Sqr(x * x + y * y + (z - {sh}) * (z - {sh}))\n  If d > {reach} Or z < {zmin} Or z > {zmax} Then\n    Error {WORKSPACE_ERROR}\n  EndIf\n",
        sh = fmt_num(r.shoulder_height_mm),
        reach = fmt_num(r.reach_mm),
        zmin = fmt_num(r.z_min_mm),
        zmax = fmt_num(r.z_max_mm),
    ));
    s.push_str("  ' Joint point: every joint inside its limit (reading a joint of a point: to confirm in session I6).\n");
    for (i, l) in r.joint_limits_deg.iter().enumerate() {
        s.push_str(&format!(
            "  ' J{}: {} to {} deg\n",
            i + 1,
            fmt_num(l[0]),
            fmt_num(l[1])
        ));
    }
    s.push_str(&format!(
        "  If PType(P(n)) = 1 Then\n    For j = 1 To {}\n      d = PAgl(P(n), j)\n      If d < JMin(j) Or d > JMax(j) Then\n        Error {WORKSPACE_ERROR}\n      EndIf\n    Next j\n  EndIf\nFend\n",
        r.joint_limits_deg.len()
    ));
    s
}

/// `NeuronSlave.prg`: a TCP command interpreter that moves the robot on request.
pub(super) fn slave(r: &Robot, max_points: u32) -> String {
    let mut s = String::new();
    s.push_str(
        "' NeuronSlave.prg: generated by Neuron. A TCP command interpreter for the digital twin.\n",
    );
    s.push_str(&format!(
        "' Robot manifest `{}`; the point table is P1 to P{max_points}.\n",
        r.name
    ));
    s.push_str("' Network statements, string parsing and reading inputs are dialect details to confirm in session I6.\n");
    s.push_str("' Commands, one per line: GO n | MOVE n | OUT b v | IN b | SPEED v | HOME.\n");
    s.push_str("' Answers: OK | ERR <code> | the value (IN). Codes: 1 syntax, 2 point outside the table, 3 workspace, 4 bit.\n\n");
    s.push_str("Function main\n");
    s.push_str("  Integer port, n, b, v, code\n");
    s.push_str("  String line$, tok$(3)\n");
    s.push_str("  Integer cnt\n");
    s.push_str("  port = 201\n");
    s.push_str("  Motor On\n");
    s.push_str("  SetNet #port, \"0.0.0.0\", 5000, CRLF, NONE, 0\n");
    s.push_str("  OpenNet #port As Server\n");
    s.push_str("  WaitNet #port\n");
    s.push_str("  Do\n");
    s.push_str("    Line Input #port, line$\n");
    s.push_str("    cnt = ParseStr(line$, tok$(), \" \")\n");
    s.push_str("    code = 0\n");
    s.push_str("    OnErr GoTo Failed\n");
    s.push_str("    Select UCase$(tok$(0))\n");
    s.push_str("      Case \"GO\", \"MOVE\"\n");
    s.push_str("        If cnt < 2 Then\n          code = 1\n        Else\n");
    s.push_str("          n = Val(tok$(1))\n");
    s.push_str(&format!(
        "          ' point table limits\n          If n < 1 Or n > {max_points} Then\n            code = 2\n          Else\n            Call NeuronCheck(n)\n            If UCase$(tok$(0)) = \"GO\" Then\n              Go P(n)\n            Else\n              Move P(n)\n            EndIf\n          EndIf\n        EndIf\n"
    ));
    s.push_str("      Case \"OUT\"\n");
    s.push_str("        If cnt < 3 Then\n          code = 1\n        Else\n          b = Val(tok$(1))\n          v = Val(tok$(2))\n          If v = 0 Then\n            Off b\n          Else\n            On b\n          EndIf\n        EndIf\n");
    s.push_str("      Case \"IN\"\n");
    s.push_str("        If cnt < 2 Then\n          code = 1\n        Else\n          b = Val(tok$(1))\n          Print #port, Sw(b)\n          GoTo Next\n        EndIf\n");
    s.push_str("      Case \"SPEED\"\n");
    s.push_str("        If cnt < 2 Then\n          code = 1\n        Else\n          Speed Val(tok$(1))\n        EndIf\n");
    s.push_str("      Case \"HOME\"\n");
    s.push_str("        Home\n");
    s.push_str("      Default\n");
    s.push_str("        code = 1\n");
    s.push_str("    Send\n");
    s.push_str("    If code = 0 Then\n      Print #port, \"OK\"\n    Else\n      Print #port, \"ERR \"; code\n    EndIf\n");
    s.push_str("Next:\n");
    s.push_str("  Loop\n");
    s.push_str("  Exit Function\n");
    s.push_str("Failed:\n");
    s.push_str(&format!(
        "  ' workspace error {WORKSPACE_ERROR} of NeuronCheck is answered with code 3, any other error with code 1\n  If Err = {WORKSPACE_ERROR} Then\n    Print #port, \"ERR 3\"\n  Else\n    Print #port, \"ERR 1\"\n  EndIf\n  EClr\n  GoTo Next\n"
    ));
    s.push_str("Fend\n");
    s
}
