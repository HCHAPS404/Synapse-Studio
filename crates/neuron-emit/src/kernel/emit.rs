//! The `kernel` emitter: state tables and the three table-independent kernels.

use super::{
    compile_nir, to_hex, Compiled, Machine, MAX_PROGRAM_WORDS, MAX_STATES, MAX_TRANSITIONS,
    MAX_VARS,
};
use crate::{nirx, Diag, EmitOptions, Emitter, Fidelity, Manifest, Package};
use neuron_nir::Nir;
use std::collections::BTreeSet;
use std::fmt::Write as _;

/// The kernel text for ST (an IEC function block).
pub const KERNEL_ST: &str = include_str!("neuron_kernel.st");
/// The kernel text for C99.
pub const KERNEL_C: &str = include_str!("nrt_kernel.c");
/// The header of the C99 kernel.
pub const KERNEL_H: &str = include_str!("nrt_kernel.h");
/// The kernel text for SPEL+.
pub const KERNEL_SPEL: &str = include_str!("neuron_kernel.spel");

/// The `kernel` emitter: every `fsm` and `sequence` of the program becomes a state table
/// (`<name>.nst.json`, `<name>.nst.hex`), run by `neuron_kernel.st`, `nrt_kernel.c` and
/// `neuron_kernel.spel`.
pub struct Kernel;

impl Emitter for Kernel {
    fn manifest(&self) -> Manifest {
        Manifest {
            name: "kernel",
            language: "state table (.nst.json, .nst.hex) with ST, C99 and SPEL+ kernels",
            dialects: &["plc", "mcu", "host", "robot", "cell"],
            profiles: &[],
            constructs: &["fsm", "sequence"],
        }
    }

    fn emit(&self, nir: &Nir, _opts: &EmitOptions) -> Result<Package, Vec<Diag>> {
        let (list, diags) = compile_nir(nir);
        if !diags.is_empty() {
            return Err(diags);
        }
        if list.is_empty() {
            return Err(vec![Diag {
                code: "NE0610",
                message: "the program has no state machine or sequence for the micro-kernel".into(),
                help: Some("the `kernel` emitter reads `fsm` and `sequence` items".into()),
                file: nirx::file(nir, 0),
                span: [0, 0],
            }]);
        }
        let mut fid = Fidelity::new("emit-kernel", "kernel.nst");
        for c in &list {
            if c.notes.is_empty() {
                fid.exact();
            }
            for n in &c.notes {
                fid.record(&c.file, c.span, n.class, &n.construct, &n.note);
            }
        }
        let mut pkg = Package::new(fid);
        let mut used = BTreeSet::new();
        let mut wiring = String::from(
            "# Micro-kernel tables\n\nGenerated by `neuron emit kernel`. A table is data: the kernels below run any table, so a machine or sequence can be replaced by downloading new words, without the vendor IDE.\n\n",
        );
        for c in &list {
            let mut base = c.table.name.clone();
            let mut n = 2;
            while !used.insert(base.clone()) {
                base = format!("{}_{n}", c.table.name);
                n += 1;
            }
            let words = match c.table.words() {
                Ok(w) => w,
                Err(e) => {
                    return Err(vec![Diag {
                        code: "NE1004",
                        message: format!("`{}`: {e}", c.table.name),
                        help: None,
                        file: c.file.clone(),
                        span: c.span,
                    }])
                }
            };
            pkg.add_text(&format!("{base}.nst.json"), c.table.to_json());
            pkg.add_text(&format!("{base}.nst.hex"), to_hex(&words));
            wiring.push_str(&describe(&base, c, words.len()));
        }
        pkg.add_text("neuron_kernel.st", KERNEL_ST.to_string());
        pkg.add_text("nrt_kernel.c", KERNEL_C.to_string());
        pkg.add_text("nrt_kernel.h", KERNEL_H.to_string());
        pkg.add_text("neuron_kernel.spel", KERNEL_SPEL.to_string());
        wiring.push_str(RUN_NOTES);
        pkg.wiring = wiring;
        Ok(pkg)
    }
}

fn describe(base: &str, c: &Compiled, words: usize) -> String {
    let t = &c.table;
    let m: &Machine = &t.machine;
    let mut s = String::new();
    let _ = writeln!(s, "## {} ({})\n", t.name, t.kind);
    let _ = writeln!(
        s,
        "- Call the kernel once per scan, every {} ms.",
        t.scan_ns as f64 / 1e6
    );
    let _ = writeln!(
        s,
        "- Table `{base}.nst.hex`: {words} words (readable form `{base}.nst.json`). States {}/{MAX_STATES}, transitions {}/{MAX_TRANSITIONS}, program words {}/{MAX_PROGRAM_WORDS}, variables {}/{MAX_VARS}.",
        m.states.len(),
        m.transitions(),
        m.program_words(),
        m.vars.len()
    );
    let _ = writeln!(
        s,
        "- Outputs are {} at the first scan.",
        if m.publish_initial {
            "all reported (a PLC publishes its outputs)"
        } else {
            "reported from their first write"
        }
    );
    s.push_str("\n| Input | Name | Type |\n|---|---|---|\n");
    for (i, p) in t.inputs.iter().enumerate() {
        let _ = writeln!(s, "| {i} | `{}` | {} |", p.name, ty(p.boolean));
    }
    s.push_str("\n| Output | Name | Type |\n|---|---|---|\n");
    for (i, p) in t.outputs.iter().enumerate() {
        let _ = writeln!(s, "| {i} | `{}` | {} |", p.name, ty(p.boolean));
    }
    s.push('\n');
    s
}

fn ty(boolean: bool) -> &'static str {
    if boolean {
        "bool (0 or 1)"
    } else {
        "16-bit integer"
    }
}

const RUN_NOTES: &str = "## Running a table

Load the words of the `.nst.hex` file (hexadecimal, a word above `7FFF` as the signed
16-bit number in the languages that have no unsigned `INT`), then call the kernel once
per scan with the inputs in the order of the tables above; it reports the outputs
that changed.

- **ST** (`neuron_kernel.st`): `kern(TBL := tbl, LEN := <words>, INP := inp)`; read
  `kern.CHG[i]` and `kern.OV[i]`; `kern.ERR` is not 0 when the table is rejected.
- **C99** (`nrt_kernel.c`, `nrt_kernel.h`): `nrt_init(&k, table, len)`, then
  `nrt_scan(&k, inputs)` and `k.chg[i]`, `k.ov[i]`.
- **SPEL+** (`neuron_kernel.spel`): fill `nk_tbl()` and `nk_len`, set `nk_in()`,
  `Call NeuronKernel`, read `nk_chg()` and `nk_ov()`.

The kernel is not part of any safety function: a hardwired E-STOP stays the authority.
";
