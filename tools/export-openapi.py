#!/usr/bin/env python
"""Export the FastAPI OpenAPI document and generate the TypeScript SDK (E2.9).

Single source of truth: the FastAPI app. This writes two committed, deterministic files:

  spec/api/openapi.json        the OpenAPI document (sorted keys, two-space indent)
  packages/sdk-ts/src/schema.ts   TypeScript types generated from that document

Both are regenerated in CI and the build fails on any `git diff`, so a model change that is
not regenerated is caught (E-R5). The generator is pure Python and makes no network call, so
CI needs only the Core API's own dependencies.

Run from the repository root (the Core API venv has `synapse_core` on the path):

    uv run --project services/core python tools/export-openapi.py        # write
    uv run --project services/core python tools/export-openapi.py --check # verify, no write
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OPENAPI_PATH = ROOT / "spec" / "api" / "openapi.json"
SDK_DIR = ROOT / "packages" / "sdk-ts"
SDK_SCHEMA = SDK_DIR / "src" / "schema.ts"

# Pin the version in the document so it never drifts with the package version.
_API_VERSION = "1.0.0"


def build_openapi() -> dict[str, object]:
    """The OpenAPI document of the Core API, made reproducible (no runtime-varying fields)."""
    sys.path.insert(0, str(ROOT / "services" / "core" / "src"))
    from synapse_core.main import create_app  # imported here so --help needs no app

    from synapse_core.schemas.errors import ErrorBody

    app = create_app()
    document = app.openapi()
    document["info"]["version"] = _API_VERSION
    # Every error response shares ErrorBody (errors.py), but it is produced by the exception
    # handlers, not declared on a route, so FastAPI does not place it in the components.
    # Add it from the model (still generated, not hand-written) so the SDK can type errors.
    components = document.setdefault("components", {})
    schemas = components.setdefault("schemas", {})
    schemas.setdefault("ErrorBody", ErrorBody.model_json_schema())
    # `openapi` version string and the rest are stable across runs already.
    return document


def dump_openapi(document: dict[str, object]) -> str:
    """Canonical JSON: sorted keys, two-space indent, trailing newline."""
    return json.dumps(document, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


# ---- TypeScript generation ---------------------------------------------------------

_TS_HEADER = """\
// Code generated by tools/export-openapi.py from spec/api/openapi.json. DO NOT EDIT.
// Regenerate with: uv run --project services/core python tools/export-openapi.py
// The SYNAPSE Core API types, derived from the single-source-of-truth OpenAPI document.

"""

_PRIMITIVE = {
    "string": "string",
    "integer": "number",
    "number": "number",
    "boolean": "boolean",
    "null": "null",
}


def _ref_name(ref: str) -> str:
    return ref.rsplit("/", 1)[-1]


def ts_type(schema: dict[str, object] | None) -> str:
    """Maps one JSON Schema node (OpenAPI 3.1 dialect) to a TypeScript type."""
    if not schema:
        return "unknown"
    if "$ref" in schema:
        return _ref_name(str(schema["$ref"]))
    if "anyOf" in schema or "oneOf" in schema:
        key = "anyOf" if "anyOf" in schema else "oneOf"
        parts = [ts_type(s) for s in schema[key]]  # type: ignore[union-attr]
        return _union(parts)
    if "allOf" in schema:
        parts = [ts_type(s) for s in schema["allOf"]]  # type: ignore[union-attr]
        return " & ".join(dict.fromkeys(parts)) or "unknown"
    if "const" in schema:
        return _literal(schema["const"])
    if "enum" in schema:
        return _union([_literal(v) for v in schema["enum"]])  # type: ignore[union-attr]
    type_field = schema.get("type")
    if isinstance(type_field, list):
        return _union([ts_type({**schema, "type": t}) for t in type_field])
    if type_field == "array":
        item = ts_type(schema.get("items"))  # type: ignore[arg-type]
        return f"Array<{item}>"
    if type_field == "object" or "properties" in schema:
        return _object_type(schema)
    if isinstance(type_field, str) and type_field in _PRIMITIVE:
        return _PRIMITIVE[type_field]
    return "unknown"


def _literal(value: object) -> str:
    if isinstance(value, str):
        return json.dumps(value)
    if isinstance(value, bool):
        return "true" if value else "false"
    if value is None:
        return "null"
    return json.dumps(value)


def _union(parts: list[str]) -> str:
    unique = list(dict.fromkeys(parts))
    return " | ".join(unique) if unique else "never"


def _object_type(schema: dict[str, object]) -> str:
    properties = schema.get("properties")
    if not isinstance(properties, dict):
        extra = schema.get("additionalProperties")
        value = ts_type(extra) if isinstance(extra, dict) else "unknown"
        return f"Record<string, {value}>"
    required = set(schema.get("required", []))  # type: ignore[arg-type]
    lines = ["{"]
    for name in properties:
        optional = "" if name in required else "?"
        lines.append(f"  {json.dumps(name)}{optional}: {ts_type(properties[name])};")
    lines.append("}")
    return "\n".join(lines)


def generate_typescript(document: dict[str, object]) -> str:
    """One `export interface`/`export type` per component schema, in sorted order."""
    components = document.get("components", {})
    schemas = components.get("schemas", {}) if isinstance(components, dict) else {}
    out = [_TS_HEADER]
    for name in sorted(schemas):
        schema = schemas[name]
        body = ts_type(schema)
        if body.startswith("{"):
            out.append(f"export interface {name} {body}\n")
        else:
            out.append(f"export type {name} = {body};\n")
    # A map of path -> methods present, so clients get a typed route list without guessing.
    paths = document.get("paths", {})
    route_lines = [f"  {json.dumps(p)}: {_methods(m)};" for p, m in sorted(paths.items())]
    out.append("export interface ApiPaths {\n" + "\n".join(route_lines) + "\n}\n")
    return "\n".join(out)


def _methods(methods: dict[str, object]) -> str:
    verbs = [m.upper() for m in methods if m in {"get", "post", "put", "delete", "patch"}]
    return _union([json.dumps(v) for v in sorted(verbs)]) or "never"


# ---- driver ------------------------------------------------------------------------


def _write_or_check(path: Path, content: str, *, check: bool) -> bool:
    """Returns True when the file is up to date (or was written); False on a mismatch."""
    current = path.read_text(encoding="utf-8") if path.exists() else None
    if check:
        if current == content:
            return True
        print(f"drift: {path.relative_to(ROOT)} is out of date; regenerate it", file=sys.stderr)
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    print(f"wrote {path.relative_to(ROOT)}")
    return True


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify files are up to date")
    args = parser.parse_args()
    document = build_openapi()
    ok = _write_or_check(OPENAPI_PATH, dump_openapi(document), check=args.check)
    ok = _write_or_check(SDK_SCHEMA, generate_typescript(document), check=args.check) and ok
    if args.check and not ok:
        print("run: uv run --project services/core python tools/export-openapi.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
