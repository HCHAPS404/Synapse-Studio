  PA2 = @('usart2.tx', 'tim2.ch3', 'adc1.in2'); PA3 = @('usart2.rx', 'tim2.ch4', 'adc1.in3');
  PA4 = @('adc1.in4'); PA5 = @('adc1.in5', 'spi1.sck', 'tim2.ch1'); PA6 = @('adc1.in6', 'spi1.miso', 'tim3.ch1');
  PA7 = @('adc1.in7', 'spi1.mosi', 'tim3.ch2'); PB0 = @('adc1.in8', 'tim3.ch3'); PB1 = @('adc1.in9', 'tim3.ch4');
  PA9 = @('usart1.tx', 'tim1.ch2'); PA10 = @('usart1.rx', 'tim1.ch3'); PB6 = @('i2c1.scl', 'tim4.ch1');
  PB7 = @('i2c1.sda', 'tim4.ch2'); PC0 = @('adc1.in10'); PC1 = @('adc1.in11')
