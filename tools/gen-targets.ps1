$lines = @(
  'schema = 1', 'name = "stm32f446"', 'source = "Generated by tools/gen-targets.ps1. Public pin-function relations (subset)."',
  'trust = "community"', 'arch = "thumbv7em"', 'mcu = "stm32f446"', 'flash_bytes = 524288', 'ram_bytes = 131072',
  'voltage_mv = 3300', '', 'peripherals = [',
